"""Solvers and repair hooks for the mechanism-design (behalf-of-others) elements.

Elements: auctions_risk, budget_balance, dsic_mechanism, ir_mechanism, top_trading.
All five were generated by GPT from few-shot templates in `behalf_of_others.ipynb` (generation repo,
21d926f^). The generator only stored an answer when GPT's `answer_<k>` string equalled an option string
exactly (utils/template_utils.py:134-137), so every 0-correct part is a question whose GPT answer was lost.
The solvers below re-derive answers from the text where the task is formal enough to do so.
"""
from __future__ import annotations

import re

import numpy as np
import pandas as pd

REPAIRS = {
    "part_dropped_only": "an unanswerable trailing part was dropped; earlier self-contained parts kept",
    "split_independent_parts": "parts of one generation are unrelated stand-alone questions; each part is its own base",
}


def _out(index, preds, stats):
    return pd.DataFrame({"pred": pd.array(preds, dtype="Int64"), "status": stats}, index=index)


def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", str(s).replace("\u2019", "'").replace("\u2018", "'")).strip()


# =============================================================================================== top_trading
NAME = r"(?:(?:Agent|Trader|Person|Player|Participant) [A-Z0-9]+|[A-Z][a-z]+(?: \d+)?)"
TOK = r"[A-Za-z0-9]+"
PFX = r"(?:(?:[Ii]tem|[Tt]oy|[Oo]bject|[Gg]ood|[Bb]ook|[Cc]ard|[Pp]ainting|[Aa]rtifact|[Cc]ollectible|[Ss]tamp|[Hh]ouse|[Cc]ommodity)\s+)?"
_OWN = re.compile(
    rf"({NAME}),? (?:who )?(?:owns|has|holds|possesses) (?:an? |the )?(?:endowment |initial endowment )?{PFX}({TOK})"
    rf"\s*(?:,|and|;)?\s*(?:and )?(?:prefers|wants|ranks|likes|preference:?|with preferences?:?|(?:his|her|their) preferences? (?:are|is):?)\s*(?:order:? )?"
    rf"((?:{PFX}{TOK}\s*(?:>|≻)\s*)+{PFX}{TOK})")
_TOP = re.compile(rf"({NAME})(?: prefers|'s preferences? (?:is|are) for| wants| would like| desires) ({NAME})'s")
_ASSIGN = re.compile(rf"({NAME}) (?:gets|receives|obtains|acquires|ends up with|takes) {PFX}({TOK})('s)?")
_KEEP = re.compile(rf"({NAME}) (?:keeps|retains|gets|receives|acquires) (?:his|her|their) own")


def _ttc(owner_of: dict, prefs: dict) -> dict | None:
    """Top trading cycles. owner_of: item -> agent; prefs: agent -> ranked items. Returns agent -> item."""
    remaining = set(prefs)
    alloc = {}
    endow = {a: i for i, a in owner_of.items()}
    while remaining:
        avail = {endow[a] for a in remaining}
        point = {}
        for a in remaining:
            top = next((i for i in prefs[a] if i in avail), endow[a])
            point[a] = owner_of[top]
        # find cycles
        done = set()
        found = False
        for a in list(remaining):
            path, x = [], a
            while x not in path and x not in done:
                path.append(x)
                x = point[x]
            if x in path:  # cycle from x
                cyc = path[path.index(x):]
                for y in cyc:
                    alloc[y] = endow[point[y]]
                    done.add(y)
                found = True
            done.update(path)
        if not found:
            return None
        remaining -= set(alloc)
    return alloc


def _first_round(point: dict) -> dict:
    """Agent -> agent whose item it gets after the first TTC round (self if not in a cycle)."""
    res = {a: a for a in point}
    for a in point:
        path, x = [], a
        while x not in path and x in point:
            path.append(x)
            x = point[x]
        if x in path:
            for y in path[path.index(x):]:
                res[y] = point[y]
    return res


def _parse_alloc(text: str, agents: set, items: set | None, owner_of: dict | None):
    """Parse 'A gets X, B gets Y' / "A gets B's" / 'Everyone keeps their own'. Returns agent -> item-owner."""
    t = _norm(text)
    if re.search(r"\b(everyone|each (?:trader|agent|participant|person)|all (?:agents|traders|participants))\b"
                 r".*\b(keeps?|retains?)\b", t, re.I):
        return {a: a for a in agents}
    res = {}
    for m in _ASSIGN.finditer(t):
        a, tok, poss = m.group(1), m.group(2), m.group(3)
        if a not in agents or tok in ("his", "her", "their"):
            continue
        if poss or (tok in agents and (items is None or tok not in items)):
            if tok not in agents:
                return None
            res[a] = tok
        else:
            if owner_of is None or tok not in owner_of:
                return None
            res[a] = owner_of[tok]
    for m in _KEEP.finditer(t):
        if m.group(1) in agents:
            res[m.group(1)] = m.group(1)
    return res or None


_CYC = r"(?:(?:trad(?:e|ing)|exchange) )?(?:cycle|allocation)"
_CORRECT_OPT = re.compile(rf"^(?:yes,? )?(?:the )?(?:proposed |suggested )?{_CYC} is (?:correct|accurate|valid|appropriate|right)\W*$", re.I)
_ALLOC_OPT = re.compile(rf"{_CYC} (?:is|should be)\s*:", re.I)


def solve_top_trading(df: pd.DataFrame) -> pd.DataFrame:
    preds, stats = [], []
    for qt, opts in zip(df.question_text, df.options):
        p, s = _solve_ttc_one(_norm(qt), list(opts))
        preds.append(p)
        stats.append(s)
    return _out(df.index, preds, stats)


def _match(opts, parsed, target, agents, strict=True):
    hits = [i for i, a in enumerate(parsed) if a is not None and a == target]
    if len(hits) == 1:
        return hits[0], "ok"
    if len(hits) > 1:
        if len({_norm(opts[i]) for i in hits}) == 1:
            return hits[0], "ok"
        return None, "multi_match"
    return None, "no_match"


def _solve_ttc_one(qt: str, opts: list[str]):
    owns = list(_OWN.finditer(qt))
    if owns:
        owner_of, prefs = {}, {}
        for m in owns:
            a, it = m.group(1), m.group(2)
            ranking = [re.sub(PFX, "", x.strip(), count=1) if re.match(PFX + TOK + "$", x.strip()) else x.strip()
                       for x in re.split(r"\s*(?:>|≻)\s*", m.group(3))]
            if a in prefs or it in owner_of:
                return None, "unparsed"
            owner_of[it] = a
            prefs[a] = ranking
        agents = set(prefs)
        items = set(owner_of)
        for a, r in prefs.items():
            if set(r) - items:
                return None, "ill_posed:preference_over_unowned_item"
            if len(set(r)) != len(r):
                return None, "ill_posed:repeated_item_in_ranking"
        alloc = _ttc(owner_of, prefs)
        if alloc is None:
            return None, "unparsed"
        target = {a: owner_of[i] for a, i in alloc.items()}  # agent -> agent whose item
        parsed = []
        for o in opts:
            if _CORRECT_OPT.search(_norm(o)):
                parsed.append("CORRECT")
                continue
            body = re.split(r":", o, maxsplit=1)[-1] if _ALLOC_OPT.search(o) else o
            if _ALLOC_OPT.search(o) or not re.search(r"cycle|no possible|cannot|impossible", o, re.I):
                pa = _parse_alloc(body, agents, items, owner_of)
                parsed.append(pa if pa and set(pa) == agents else None)
            else:
                parsed.append(None)
        is_err = any(x == "CORRECT" for x in parsed) or re.search(r"propos|suggest", qt, re.I)
        if is_err:
            m = re.search(r"(?:propos|suggest)\w*", qt, re.I)
            prop = _parse_alloc(qt[m.end():], agents, items, owner_of) if m else None
            if not prop or set(prop) != agents:
                return None, "unparsed"
            if prop == target:
                hits = [i for i, x in enumerate(parsed) if x == "CORRECT"]
                if len(hits) == 1:
                    # an option restating the proposal as "the correct cycle is: <same>" would also be right
                    if any(x == target for x in parsed):
                        return None, "multi_match"
                    return hits[0], "ok"
                return (None, "no_match") if not hits else (None, "multi_match")
            return _match(opts, parsed, target, agents)
        return _match(opts, parsed, target, agents)

    tops = list(_TOP.finditer(qt))
    if tops:
        point = {}
        for m in tops:
            if m.group(1) in point:
                return None, "unparsed"
            point[m.group(1)] = m.group(2)
        agents = set(point)
        if set(point.values()) - agents or any(a == b for a, b in point.items()):
            return None, "unparsed"
        target = _first_round(point)
        parsed = []
        for o in opts:
            pa = _parse_alloc(o, agents, None, None)
            if pa is not None:
                pa = {**{a: a for a in agents}, **pa} if re.search(r"keeps?|retains?", o) else pa
            parsed.append(pa if pa and set(pa) == agents else None)
        return _match(opts, parsed, target, agents)
    if ">" not in qt and not re.search(r"prefers? \w+'s|'s preferences", qt):
        return None, "ill_posed:missing_preferences"
    return None, "unparsed"



# =============================================================================================== auctions_risk
# Private-value auctions with non-neutral risk attitudes (Krishna, Auction Theory ch. 4; paper Element 4.4.b):
#   risk-averse bidders: first-price (and the strategically equivalent Dutch) auction > second-price/English;
#   risk-seeking bidders: second-price (and the equivalent English / Japanese / open ascending) > first-price/Dutch.
# An option "wins" if it belongs to the revenue-maximising equivalence class; other formats (all-pay, lottery,
# fixed-price, ...) are treated as distractors (as in the templates). >1 option of the winning class = ill-posed.
DUTCH_EQUIV_FIRST_PRICE = True  # Dutch == first-price sealed bid (strategic equivalence); set False for template intent


def _auction_class(o: str) -> str:
    t = o.lower()
    if re.search(r"all[- ]pay|lotter|random|fixed[- ]price|penny|reverse|double|walrasian|absolute|winner|third|ipo|candle", t):
        return "other"
    if re.search(r"first[- ]price|pay[- ]as[- ]bid|discriminatory", t):
        return "first"
    if re.search(r"dutch|descending|descend", t):
        return "first" if DUTCH_EQUIV_FIRST_PRICE else "dutch"
    if re.search(r"second[- ]price|vickrey|english|ascending|japanese|open[- ]outcry|open[- ]cry|clock", t):
        return "second"
    return "other"


def solve_auctions_risk(df: pd.DataFrame) -> pd.DataFrame:
    preds, stats = [], []
    for qt, opts, ty in zip(df.question_text, df.options, df.type):
        t = _norm(qt).lower()
        av = bool(re.search(r"risk[- ]?avers", t))
        sk = bool(re.search(r"risk[- ]?(?:seek|lov|tak|tolera|prefer|embrac|hungry|appetit)", t))
        if av == sk:  # text silent or both: fall back on metadata type
            att = {"risk_averse": "averse", "risk_seeking": "seeking"}.get(str(ty))
            if att is None:
                preds.append(None); stats.append("unparsed"); continue
        else:
            att = "averse" if av else "seeking"
        if re.search(r"\b(lowest|minimi[sz]e (?:the )?(?:revenue|bids))\b", t):
            preds.append(None); stats.append("unparsed"); continue
        cls = [_auction_class(o) for o in opts]
        want = "first" if att == "averse" else "second"
        hits = [i for i, c in enumerate(cls) if c == want]
        if len(hits) == 1:
            preds.append(hits[0]); stats.append("ok")
        elif not hits:
            preds.append(None); stats.append("no_match")
        else:
            preds.append(None)
            stats.append("ill_posed:equivalent_formats" if att == "seeking" or not DUTCH_EQUIV_FIRST_PRICE
                         else "ill_posed:dutch_equiv_first_price" if any("dutch" in opts[i].lower() or "descend" in opts[i].lower() for i in hits)
                         else "ill_posed:equivalent_formats")
    return _out(df.index, preds, stats)



# =============================================================================================== dsic_mechanism
# Part 0: "Is this mechanism DSIC?" for a sealed-bid single-item auction.  Truthful bidding is a dominant strategy
# in the second-price (Vickrey) auction only.  First-price: bid shading pays.  Third-price (winner pays the
# third-highest bid): NOT DSIC either -- a bidder whose value lies between the highest and second-highest
# competing bids gains by overbidding (wins, pays the third-highest bid < value).  The templates
# (behalf_of_others.ipynb cells 15/23/31) mark third-price "Yes", which is wrong.
# Later parts: "how much does the winner pay / what revenue" under k-th price with truthful bids -> k-th highest.
_YES = re.compile(r"^(?:(?:option )?[a-d][).:]\s*)?yes\b", re.I)
_NO = re.compile(r"^(?:(?:option )?[a-d][).:]\s*)?no\b", re.I)
_MONEY = re.compile(r"\$\s?(\d[\d,]*(?:\.\d+)?)\s*(k|K|thousand|million|mn|m|M|billion|bn|B)?\b")


def _money_vals(t: str) -> list[float]:
    out = []
    for m in _MONEY.finditer(t):
        v = float(m.group(1).replace(",", ""))
        u = (m.group(2) or "").lower()
        v *= {"k": 1e3, "thousand": 1e3, "million": 1e6, "mn": 1e6, "m": 1e6, "billion": 1e9, "bn": 1e9, "b": 1e9}.get(u, 1)
        out.append(v)
    return out


def _mech_kind(t: str) -> set:
    t = t.lower()
    t = re.sub(r"(?:instead of|rather than|not|as opposed to) (?:paying |having to pay |pay )?(?:their|its|his|her|the) (?:own )?"
               r"(?:bid|bid amount|highest bid|winning bid)\b", " ", t)
    t = re.sub(r"(?:unlike|compared to|compared with|versus|as opposed to|instead of) (?:a|an|the) (?:typical |standard |usual |traditional )?"
               r"[a-z-]+(?: sealed[- ]bid)?(?: auction| bid(?: price)?)", " ", t)
    named = {k for k, pat in ((1, r"first[- ]price"), (2, r"second[- ]price|vickrey"), (3, r"third[- ]price")) if re.search(pat, t)}
    if len(named) == 1 and not re.search(r"instead of|rather than|unlike|compared|versus|\bvs\b|switch", t):
        return named
    k = set()
    if re.search(r"third[- ]highest|third[- ]price|third[- ]lowest", t):
        k.add(3)
    if re.search(r"second[- ]highest|second[- ]price|vickrey|second[- ]lowest|next[- ]highest", t):
        k.add(2)
    if re.search(r"first[- ]price|pay[- ]as[- ]bid|pay(?:s|ing)? (?:to )?(?:the (?:council|government|seller|city) )?(?:the )?(?:exact |full )?"
                 r"(?:(?:amount|price|value) of )?(?:their|its|his|her) (?:own )?(?:highest |winning )?bid"
                 r"|pay(?:s|ing)? (?:the )?(?:exact )?(?:amount|price) (?:they|it) (?:bid|submitted)|pay what (?:they|it) bid"
                 r"|pay(?:s|ing)? the (?:winning )?bid amount|winning bid becomes the price|pay(?:s|ing)? (?:the )?(?:exact )?amount (?:they |it )?bid(?! by)", t):
        k.add(1)
    return k


_NON_AUCTION = re.compile(r"sum of (?:all )?(?:the )?(?:bids|valuations|contributions|stated)|total (?:of )?(?:the )?(?:bids|stated|"
                          r"contributions|valuations)|threshold|equal share|each (?:resident|participant|citizen)s? (?:will )?pay|"
                          r"clarke|groves|vcg|pivot|lottery|random|all[- ]pay|budget|posted price|fixed price|contribut|equal (?:portion|part|amount)|"
                          r"funded if|cost of (?:the|building)|total (?:value|cost)|each (?:resident|citizen|household)|"
                          r"split|shared|proportion|multiple (?:items|units|winners)|top (?:two|three)|two (?:features|projects)|"
                          r"combinatorial|bundle|(?:firms|bidders|companies|investors|developers) with the (?:highest|top) bids", re.I)


def solve_dsic(df: pd.DataFrame) -> pd.DataFrame:
    preds = [None] * len(df)
    stats = ["unparsed"] * len(df)
    pos = {ix: i for i, ix in enumerate(df.index)}
    for _, g in df.groupby("base_id", sort=False):
        g = g.sort_values("part")
        first = g.iloc[0]
        kind0 = _mech_kind(first.question_text)
        for ix, r in g.iterrows():
            i = pos[ix]
            t = _norm(r.question_text)
            opts = list(r.options)
            if any(o.strip() == "" for o in opts):
                stats[i] = "ill_posed:empty_options"
                continue
            isdsic = re.search(r"dominant[- ]strategy[- ]incentive|incentiv\w* to bid (?:their|its) true|\bDSIC\b|truth[- ]?telling|truthful(?:ly)? .*dominant|"
                               r"dominant strategy", t, re.I) and re.search(r"\?\s*$|is this|does this", t, re.I)
            yn = [bool(_YES.search(o.strip())) for o in opts], [bool(_NO.search(o.strip())) for o in opts]
            if isdsic and sum(yn[0]) == 1 and sum(yn[1]) == 1 and len(opts) == 2:
                k = _mech_kind(t) or (kind0 if r.part > 0 else set())
                if _NON_AUCTION.search(t) or re.search(r"lowest", t, re.I) and not re.search(r"highest", t, re.I) and False:
                    continue
                if len(k) != 1:
                    stats[i] = "unparsed" if not k else "ill_posed:contradictory_mechanism"
                    continue
                ans = (2 in k)
                preds[i] = yn[0].index(True) if ans else yn[1].index(True)
                stats[i] = "ok"
                continue
            p, st = _dsic_payment(t, opts, kind0, r.type)
            preds[i], stats[i] = p, st
    return _out(df.index, preds, stats)


_NUMW = {"two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8}
_AGENT_N = (r"(?:companies|firms|bidders|developers|investors|contractors|participants|buyers|parties|agencies|"
            r"entities|organizations|organisations|providers|insurers|hospitals|teams|corporations|businesses|"
            r"artists|builders|operators|vendors|suppliers|groups|individuals|agents|players|banks|funds|startups|"
            r"construction companies|construction firms|real estate developers|property developers|[a-z]+ (?:companies|firms))")


def _n_bidders(t: str):
    m = re.search(rf"\b(two|three|four|five|six|seven|eight|\d)\s+(?:[a-z-]+\s+)?{_AGENT_N}\b", t, re.I)
    if m:
        w = m.group(1).lower()
        return _NUMW.get(w) or int(w)
    return None


def _dsic_payment(t: str, opts: list[str], kind0: set, ty) -> tuple:
    """'How much does the winner pay / what revenue' with truthful bids; options are plain amounts."""
    if not re.search(r"how much|what (?:amount|price|will be the price|is the price)|price paid|revenue|amount .* (?:pay|receive)|"
                     r"(?:pay|receive)s? .*\?", t, re.I):
        return None, "unparsed"
    if re.search(r"sav(?:e|ing)|surplus|utility|profit|welfare|cost|lowest|less than|more than|shade|reserve|"
                 r"turn out|increase|decrease|instead|difference|expected|each of|total payment|paid by each|"
                 r"will be paid|gets paid|\\bbe paid\\b|paid by|contractor|procure|receive payment|% |percent|if .* had|changes?|deviat|collud", t, re.I):
        return None, "unparsed"
    if _NON_AUCTION.search(t):
        return None, "unparsed"
    k = _mech_kind(t) or kind0
    if len(k) != 1:
        k = {"first_price": {1}, "second_price": {2}, "third_price": {3}}.get(str(ty), set()) if not k else k
    if len(k) != 1:
        return None, "unparsed"
    (k,) = k
    vals = _money_vals(t)
    n = _n_bidders(t)
    if n is None or n != len(vals):
        return None, "unparsed"
    if len(vals) < k or len(vals) != len(set(vals)) or len(vals) > 8:
        return None, "unparsed"
    target = sorted(vals, reverse=True)[k - 1]
    ov = []
    for o in opts:
        o2 = o.strip()
        if not re.fullmatch(r"(?:[A-Da-d][).:]\s*)?\$\s?[\d,.]+\s*(?:k|K|thousand|million|mn|m|M|billion|bn|B)?", o2):
            return None, "unparsed"
        v = _money_vals(o2)
        ov.append(v[0] if v else None)
    hits = [i for i, v in enumerate(ov) if v is not None and abs(v - target) <= 1e-6 * max(1.0, target)]
    if len(hits) == 1:
        return hits[0], "ok"
    return (None, "no_match") if not hits else (None, "multi_match")



# =============================================================================================== hooks
def _add_repair(df, mask, rid):
    df.loc[mask, "repair"] = df.loc[mask, "repair"].map(lambda r: list(r) + [rid])
    return df


def fix_split_parts(df: pd.DataFrame) -> pd.DataFrame:
    """budget_balance: the k parts of one generation are k unrelated stand-alone yes/no questions
    (GPT wrote several examples per call); make every part its own base so a bad part drops alone."""
    df = df.copy()
    multi = df.groupby("base_id").part.transform("size") > 1
    df.loc[multi, "base_id"] = df.loc[multi, "base_id"] + "-" + df.loc[multi, "part"].astype(str)
    df.loc[multi, "part"] = 0
    return _add_repair(df, multi, "split_independent_parts")


def postfix_keep_prefix(df: pd.DataFrame) -> pd.DataFrame:
    """Later parts build on earlier ones ("Continuing with the scenario above ..."), earlier parts are
    self-contained.  If part p is dropped, drop parts >= p but keep parts < p.  The dropped rows get a
    private base_id suffix so repair.py's whole-base sibling rule does not remove the kept prefix."""
    df = df.copy()
    dropped = df["drop"].notna()
    first_bad = df[dropped].groupby("base_id").part.min()
    fb = df.base_id.map(first_bad)
    later = fb.notna() & (df.part > fb) & df["drop"].isna()
    df.loc[later, "drop"] = "sibling_part_dropped"
    tail = fb.notna() & (df.part >= fb)
    keep = fb.notna() & (df.part < fb)
    df.loc[tail & keep.groupby(df.base_id).transform("any"), "base_id"] = df.base_id + "#dropped_tail"
    df = _add_repair(df, keep, "part_dropped_only")
    # two kept bases sharing an identical part text but differing elsewhere (schema forbids duplicate
    # (question_text, part)): keep the base with more kept parts, drop the other(s) whole.
    live = df[df["drop"].isna()]
    nparts = live.groupby("base_id").size()
    sig = live.sort_values("part").groupby("base_id").question_text.agg("\x1f".join)
    for _, g in live[live.duplicated(["question_text", "part"], keep=False)].groupby(["question_text", "part"]):
        bases = sorted(g.base_id.unique(), key=lambda b: (-nparts[b], b))
        if sig[bases].nunique() == 1:  # exact duplicate bases: left to repair.py's dedupe
            continue
        for b in bases[1:]:
            m = (df.base_id == b) & df["drop"].isna()
            df.loc[m, "drop"] = "dedup_part_text_of:" + bases[0]
    return df


def postfix_drop_conflicts(df: pd.DataFrame) -> pd.DataFrame:
    """Identical question text + identical option set but different answers: GPT labelled the same question
    both ways; no answer can be trusted, drop all copies (repair.py's dedupe would silently keep the first)."""
    df = df.copy()
    live = df["drop"].isna() & df.correct_text.notna()
    key = df.question_text + "\x1f" + df.part.astype(str) + "\x1f" + df.options.map(lambda o: "\x1e".join(sorted(o)))
    n_ans = df[live].groupby(key[live]).correct_text.nunique()
    bad = key.isin(n_ans[n_ans > 1].index) & live
    df.loc[bad, "drop"] = "conflicting_duplicate_answers"
    return df


def _chain(*fns):
    def run(df):
        for f in fns:
            df = f(df)
        return df
    return run


