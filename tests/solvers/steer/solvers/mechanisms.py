# Independent solvers for the templated ir_mechanism / budget_balance / auctions_risk questions produced by
# src/filler_tools/mechanism_tools.py (design: audit/DECISIONS.md, "Behalf-of-others redesign").  They parse the
# rendered question text and options only; nothing is imported from the filler.  Each returns the index of the
# single correct option, or None if the text cannot be parsed or no / several options match.
from fractions import Fraction

_R_MONEY = re.compile(r"\$([\d,]+)")
_R_NAMED_VAL = re.compile(r"\b([A-Z][a-z]+) \$([\d,]+)")
_R_NUMWORD = re.compile(r"\b(two|three|four|five|six|seven|eight)\b", re.I)
_NUMW_ALL = {"two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8}
_R_NAMES = r"((?:[A-Z][a-z]+, )*[A-Z][a-z]+(?: and [A-Z][a-z]+)?)"


def _usd(s: str) -> int:
    return int(s.replace(",", ""))


def _split_names(s: str) -> list:
    return [x for x in re.split(r", | and ", s) if x]


def _unique(hits: list):
    return hits[0] if len(hits) == 1 else None


def _clarke(values: dict, share) -> tuple:
    """Clarke pivot mechanism with equal cost shares. Returns (built, {name: tax})."""
    r = {a: v - share for a, v in values.items()}
    total = sum(r.values())
    built = total >= 0
    tax = {}
    for a in r:
        others = total - r[a]
        tax[a] = abs(others) if (others >= 0) != built else 0
    return built, tax


def regen_ir_net_utilities(question: str):
    """(net utility of participating per person, outside option) parsed from an ir_mechanism question."""
    q = _norm(question)
    cost = Fraction(_usd(_R_MONEY.search(q).group(1)))  # the first amount in every frame is the cost
    values = {a: Fraction(_usd(v)) for a, v in _R_NAMED_VAL.findall(q)}
    n = len(values)
    if n < 2:
        return None
    m = re.search(r"worth \$([\d,]+) to each", q)
    outside = Fraction(_usd(m.group(1))) if m else Fraction(0)
    if "Clarke" in q:
        built, tax = _clarke(values, cost / n)
        net = {a: (v - cost / n if built else 0) - tax[a] for a, v in values.items()}
    elif "usage points" in q:
        pts = {a: int(p) for a, p in re.findall(r"\b([A-Z][a-z]+): (\d+) points?\b", q)}
        if set(pts) != set(values):
            return None
        net = {a: v - cost * pts[a] / sum(pts.values()) for a, v in values.items()}
    elif re.search(r"proportional to their value", q):
        tot = sum(values.values())
        if tot < cost:
            return None
        net = {a: v - cost * v / tot for a, v in values.items()}
    elif re.search(r"split equally|equal share|equal one-\w+ share", q):
        net = {a: v - cost / n for a, v in values.items()}
    else:
        return None
    return net, outside


def solve_regen_ir_mechanism(question: str, options: list):
    """Which participant would be better off not participating (or 'Everyone ...')?"""
    parsed = regen_ir_net_utilities(question)
    if parsed is None:
        return None
    net, outside = parsed
    losers = [a for a in net if net[a] < outside]
    if len(losers) > 1:
        return None
    if losers:
        return _unique([i for i, o in enumerate(options) if o.strip() == losers[0]])
    return _unique([i for i, o in enumerate(options) if re.match(r"everyone\b.*\bparticipat", o.strip(), re.I)])


def solve_regen_budget_balance(question: str, options: list):
    """Balanced / surplus of $X / deficit of $X, under the definition the question states."""
    q = _norm(question)
    cost = _usd(_R_MONEY.search(q).group(1))
    if re.search(r"collects exactly the cost: no surplus and no deficit|equals the cost exactly", q):
        weak = False
    elif re.search(r"never runs a deficit|weakly balanced", q):
        weak = True
    else:
        return None
    if "Clarke" in q:
        values = {a: Fraction(_usd(v)) for a, v in _R_NAMED_VAL.findall(q)}
        if len(values) < 2:
            return None
        built, tax = _clarke(values, Fraction(cost, len(values)))
        if not built:
            return None
        delta = sum(tax.values())
    elif "equal share of the cost" in q:
        delta = 0  # the equal shares sum to the cost
        for names, amt in re.findall(rf"(?:In addition|Also), {_R_NAMES} (?:each pay|pays) an? \$([\d,]+) [a-z -]+? "
                                     r"into the same fund", q):
            delta += len(_split_names(names)) * _usd(amt)
        for names, amt in re.findall(rf"(?:In addition|Also), {_R_NAMES} (?:each receive|receives) an? \$([\d,]+) "
                                     r"[a-z -]+? paid out of the fund", q):
            delta -= len(_split_names(names)) * _usd(amt)
    else:
        pays = [_usd(x) for x in re.findall(r"\b[A-Z][a-z]+ pays \$([\d,]+)", q)]
        rebates = [_usd(x) for x in re.findall(r"\b[A-Z][a-z]+ receives a rebate of \$([\d,]+)", q)]
        if not pays:
            return None
        delta = sum(pays) - sum(rebates) - cost
    hits = []
    for i, o in enumerate(options):
        o = o.strip()
        label_ok = re.match(r"budget balanced\b", o, re.I) is not None  # vs "Not budget balanced"
        if re.search(r"collects exactly the cost", o):
            val = 0
        elif (m := re.search(r"surplus of \$([\d,]+)", o)):
            val = _usd(m.group(1))
        elif (m := re.search(r"deficit of \$([\d,]+)", o)):
            val = -_usd(m.group(1))
        else:
            continue
        should_label = delta == 0 or (weak and delta > 0)
        if val == delta and label_ok == should_label:
            hits.append(i)
    return _unique(hits)


def _format_class(s: str):
    t = s.lower()
    if re.search(r"first-price|dutch|descending", t):
        return "first"
    if re.search(r"second-price|vickrey|english|ascending", t):
        return "second"
    if re.search(r"\bsame\b", t):
        return "same"
    return None


def solve_regen_auctions_risk(question: str, options: list):
    """Risk-attitude revenue ranking; expected revenue V(n-1)/(n+1); first-price bid v(n-1)/n."""
    q = _norm(question)
    m = _R_NUMWORD.search(q)
    mV = re.search(r"between \$0 and \$([\d,]+)", q)
    if not m or not mV:
        return None
    n = _NUMW_ALL[m.group(1).lower()]
    V = Fraction(_usd(mV.group(1)))
    numeric = all(re.fullmatch(r"\$[\d,]+", o.strip()) for o in options)
    if numeric:
        if not re.search(r"risk-neutral", q):
            return None
        mv = re.search(r"value is \$([\d,]+)", q)
        if mv:  # first-price equilibrium bid
            if not re.search(r"first-price", q):
                return None
            target = Fraction(_usd(mv.group(1))) * (n - 1) / n
        else:  # expected revenue of any standard auction = E[second-highest value]
            target = V * (n - 1) / (n + 1)
        return _unique([i for i, o in enumerate(options) if _usd(o.strip()[1:]) == target])
    att = [a for a, pat in (("averse", r"risk-averse"), ("neutral", r"risk-neutral"), ("seeking", r"risk-seeking"))
           if re.search(pat, q)]
    if len(att) != 1:
        return None
    want = {"averse": "first", "neutral": "same", "seeking": "second"}[att[0]]
    cls = [_format_class(o) for o in options]
    if sorted(c for c in cls if c) != sorted(set(c for c in cls if c)):
        return None  # two formats of the same equivalence class on offer: ill-posed
    return _unique([i for i, c in enumerate(cls) if c == want])


