def display_name_for_element(element_name: str) -> str:
    return ELEMENT_DISPLAY_NAMES.get(
        element_name,
        element_name.replace("_", " ").replace("-", " ").title(),
    )


def taxonomy_for_element(element_name: str) -> dict:
    setting, module = ELEMENT_TAXONOMY.get(
        element_name,
        ("Unmapped", "Needs taxonomy assignment"),
    )
    return {
        "setting": setting,
        "module": module,
        "element": element_name,
        "display_name": display_name_for_element(element_name),
    }


EXCLUDED_ELEMENTS = {
    "certainty_effect",
    "reflection_effect",
    "completeness",
    "completeness_risk",
    "feasibility",
}


def is_non_strategic_element(element_name: str) -> bool:
    if element_name in EXCLUDED_ELEMENTS:
        return False
    return taxonomy_for_element(element_name)["setting"] in NON_STRATEGIC_SETTINGS


def element_category_summary(element_name: str, manifest_entry: dict | None) -> dict:
    manifest_entry = manifest_entry or {}
    return {
        **taxonomy_for_element(element_name),
        "types": manifest_entry.get("types", []),
        "domains": manifest_entry.get("domains", []),
        "perspectives": manifest_entry.get("tags", []),
        "difficulty_levels": manifest_entry.get("difficulty_levels", []),
    }
